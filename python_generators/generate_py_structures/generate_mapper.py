#!/usr/bin/env python3
import argparse
import importlib.util
import os
import re
import sys

def load_structures(ids_name, structures_file):
    """Loads the structures module dynamically."""
    if os.path.isdir(structures_file):
        structures_file = os.path.join(structures_file, f"{ids_name}_structures.py")
        
    spec = importlib.util.spec_from_file_location(ids_name, structures_file)
    if spec is None:
        print(f"Error: Could not load structures from {structures_file}", file=sys.stderr)
        sys.exit(1)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return {s.name: s for s in module.structures}

def generate_mapper(ids_name, structures_file, output_file):
    structures_map = load_structures(ids_name, structures_file)
    
    root_struct_name = ids_name
    if root_struct_name not in structures_map and f"{root_struct_name}_struct" in structures_map:
        root_struct_name = f"{root_struct_name}_struct"

    if root_struct_name not in structures_map:
        print(f"Error: Root structure '{root_struct_name}' not found.", file=sys.stderr)
        sys.exit(1)

    class_name = f"West{ids_name.capitalize()}Mapper"

    content = f"""// Auto-generated mapper for {ids_name}
// Generated by generate_mapper.py

#pragma once

#include <libtokamap.hpp>
#include <nlohmann/json.hpp>
#include <string>
#include <vector>
#include <iostream>
#include <algorithm>
#include <bit>
#include <typeindex>

class {class_name} {{
public:
    void map_all(libtokamap::MappingHandler& mapping_handler, nlohmann::json& trace, const std::string& mapping, int shot) {{
        std::string root_path = "{ids_name}";
"""

    var_counter = 0

    def get_typeid_string(type_name):
        if "string" in type_name: return "std::type_index{typeid(char)}"
        if "double" in type_name: return "std::type_index{typeid(double)}"
        if "float" in type_name: return "std::type_index{typeid(float)}"
        if "uint64_t" in type_name: return "std::type_index{typeid(uint64_t)}"
        if "int64_t" in type_name: return "std::type_index{typeid(int64_t)}"
        if "int" in type_name: return "std::type_index{typeid(int)}"
        return "std::type_index{typeid(void)}"
    
    def get_data_type(type_name):
        # Types Non-signés (du plus grand au plus petit)
        if "uint64_t" in type_name: return "libtokamap::DataType::UInt64"
        if "uint32_t" in type_name: return "libtokamap::DataType::UInt32"
        if "uint16_t" in type_name: return "libtokamap::DataType::UInt16"
        if "uint8_t" in type_name:  return "libtokamap::DataType::UInt8"
        
        # Types Signés (du plus grand au plus petit)
        if "int64_t" in type_name:  return "libtokamap::DataType::Int64"
        if "int32_t" in type_name:  return "libtokamap::DataType::Int32"
        if "int16_t" in type_name:  return "libtokamap::DataType::Int16"
        if "int8_t" or "std::string" in type_name:   return "libtokamap::DataType::Int8"
        
        # Cas particulier "int" (souvent mappé sur Int32 par défaut)
        if "int" in type_name:      return "libtokamap::DataType::Int32"
        
        # Virgule flottante
        if "double" in type_name:   return "libtokamap::DataType::Double"
        if "float" in type_name:    return "libtokamap::DataType::Float"
        
        # Valeur par défaut si rien n'est trouvé
        return "libtokamap::DataType::Unknown"

    def process_struct(struct_name, path_var, indent_level):
        nonlocal var_counter
        out = ""
        indent = "    " * indent_level
        
        # Resolve struct name alias (e.g. FluxLoop -> FluxLoop_struct)
        if struct_name not in structures_map and f"{struct_name}_struct" in structures_map:
            struct_name = f"{struct_name}_struct"
            
        if struct_name not in structures_map:
            return out
            
        struct_def = structures_map[struct_name]
        
        for field in struct_def.fields:
            
            if field.is_vector and field.is_struct:
                # Array of structures
                var_counter += 1
                array_name = field.name.replace("_vect", "")
                suffix = f"{indent_level}_{var_counter}"
                size_var = f"size_{array_name}_{suffix}"
                loop_var = f"i_{array_name}_{suffix}"
                
                field_path_expr = f'{path_var} + "/{array_name}"'

                out += f'\n{indent}// Array: {array_name}\n'
                out += f'{indent}uint64_t {size_var} = map_dimension(mapping_handler, trace, mapping, {field_path_expr}, shot);\n'
                out += f'{indent}for (uint64_t {loop_var} = 0; {loop_var} < {size_var}; ++{loop_var}) {{\n'
                
                child_path_var = f"path_{array_name}_{suffix}"
                out += f'{indent}    std::string {child_path_var} = {field_path_expr} + "[" + std::to_string({loop_var}) + "]";\n'
                
                # Extract struct name
                type_name = field.type_name
                match = re.search(r'<([\w: ]+)>', type_name)
                child_struct_name = match.group(1) if match else type_name.replace('*', '')
                child_struct_name = child_struct_name.strip()
                
                out += process_struct(child_struct_name, child_path_var, indent_level + 1)
                out += f'{indent}}}\n'
                
            elif field.is_struct:
                # Single structure
                var_counter += 1
                suffix = f"{indent_level}_{var_counter}"
                out += f'\n{indent}// Structure: {field.name}\n'
                child_path_var = f"path_{field.name}_{suffix}"
                single_struct_path_expr = f'{path_var} + "/{field.name}"'
                out += f'{indent}std::string {child_path_var} = {single_struct_path_expr};\n'
                
                child_struct_name = field.type_name.replace('*', '').strip()
                out += process_struct(child_struct_name, child_path_var, indent_level + 1)
                
            else:
                # Leaf field
                leaf_path_expr = f'{path_var} + "/{field.name}"'
               # typeid_str = get_typeid_string(field.type_name)
                typeid_str = get_data_type(field.type_name)
                
                rank = field.rank
                
                effective_rank = rank
                if "string" in field.type_name and rank == 0:
                    effective_rank = 1
                
                out += f'{indent}map_field(mapping_handler, trace, mapping, {leaf_path_expr}, shot, {typeid_str}, {effective_rank});\n'
        
        return out

    content += process_struct(root_struct_name, "root_path", 2)

    content += """    }

private:
    uint64_t map_dimension(libtokamap::MappingHandler& mapping_handler, nlohmann::json& trace, const std::string& mapping,
                 const std::string& path, int shot)
    {
        // This function is for getting array sizes. We expect a scalar integer.
        std::type_index data_type = std::type_index{typeid(uint64_t)};
        int rank = 0;
        nlohmann::json extra_attributes = {{"shot", shot}};

        try {
            auto result = mapping_handler.map(mapping, path, data_type, rank, extra_attributes);

            if (!result.trace().empty()) {
                trace[path] = result.trace();
            }

            if (result.type_index() == std::type_index{typeid(uint64_t)}) {
                return *std::bit_cast<uint64_t*>(result.buffer());
            }
            if (result.type_index() == std::type_index{typeid(int)}) {
                return static_cast<uint64_t>(*std::bit_cast<int*>(result.buffer()));
            }
        } catch (const std::exception& e) {
            // std::cerr << "Warning: could not map dimension for '" << path << "': " << e.what() << std::endl;
        }
        return 0;
    }

    void map_field(libtokamap::MappingHandler& mapping_handler, nlohmann::json& trace, const std::string& mapping,
                 const std::string& path, int shot, libtokamap::DataType data_type, int rank)
    {
        nlohmann::json extra_attributes = {{"shot", shot}};

        try {
            auto result = mapping_handler.map(mapping, path, data_type, rank, extra_attributes);

            if (!result.trace().empty()) {
                trace[path] = result.trace();
            }
        } catch (const std::exception& e) {
            // Ignore errors for individual fields to allow partial mapping
            // std::cerr << "Warning: could not map field '" << path << "': " << e.what() << std::endl;
        }
    }
};
"""

    with open(output_file, 'w') as f:
        f.write(content)
    
    print(f"Successfully generated mapper in '{output_file}'")

if __name__ == "__main__":
    parser = argparse.ArgumentParser(description="Generate C++ mapper class for WEST.")
    parser.add_argument("ids_name", type=str, help="Name of the IDS (e.g., 'magnetics').")
    parser.add_argument("structures_file", type=str, help="Path to the Python structures file.")
    parser.add_argument("-o", "--output", dest="output_file", help="Output C++ file.")
    
    args = parser.parse_args()

    output_file = args.output_file
    if not output_file:
        output_file = f"west_{args.ids_name}_mapper.hpp"

    generate_mapper(args.ids_name, args.structures_file, output_file)