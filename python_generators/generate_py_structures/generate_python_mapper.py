#!/usr/bin/env python3
import argparse
import importlib.util
import os
import re
import sys

def load_structures(ids_name, structures_file):
    """Loads the structures module dynamically."""
    if os.path.isdir(structures_file):
        structures_file = os.path.join(structures_file, f"{ids_name}_structures.py")
        
    spec = importlib.util.spec_from_file_location(ids_name, structures_file)
    if spec is None:
        print(f"Error: Could not load structures from {structures_file}", file=sys.stderr)
        sys.exit(1)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return {s.name: s for s in module.structures}

def generate_python_mapper(ids_name, structures_file, output_file):
    structures_map = load_structures(ids_name, structures_file)
    
    root_struct_name = ids_name
    if root_struct_name not in structures_map and f"{root_struct_name}_struct" in structures_map:
        root_struct_name = f"{root_struct_name}_struct"

    if root_struct_name not in structures_map:
        print(f"Error: Root structure '{root_struct_name}' not found.", file=sys.stderr)
        sys.exit(1)

    content = f"""# Auto-generated Python mapper for {ids_name}
# Generated by generate_python_mapper.py

import libtokamap
import numpy as np

def _map_field(mapper, experiment, path, shot):
    try:
        res = mapper.map(experiment, path, {{'shot': shot}})
        if hasattr(res, 'dtype') and res.dtype.kind in ('S', 'U'):
            # Handle byte strings or fixed-length strings
            if res.size == 1:
                return res.item().decode() if isinstance(res.item(), bytes) else res.item()
            return [x.decode() if isinstance(x, bytes) else x for x in res.flatten()]
        return res
    except Exception:
        # print(f"Warning: could not map field '{{path}}'")
        return None

def _map_dimension(mapper, experiment, path, shot):
    res = _map_field(mapper, experiment, path, shot)
    if res is not None:
        try:
            return int(np.atleast_1d(res)[0])
        except (ValueError, TypeError, IndexError):
            return 0
    return 0

def map_all(mapper: libtokamap.Mapper, experiment: str, shot: int):
    root_path = "{ids_name}"
"""

    def process_struct(struct_name, path_expr, indent_level):
        out = ""
        indent = "    " * indent_level
        
        if struct_name not in structures_map and f"{struct_name}_struct" in structures_map:
            struct_name = f"{struct_name}_struct"
            
        if struct_name not in structures_map:
            return out
            
        struct_def = structures_map[struct_name]
        
        for field in struct_def.fields:
            if field.is_vector and field.is_struct:
                # Array of structures
                array_name = field.name.replace("_vect", "")
                field_path = f'{{path_prefix}}/{array_name}'
                
                out += f'\n{indent}# Array: {array_name}\n'
                size_var = f"size_{array_name}_{indent_level}"
                out += f'{indent}{size_var} = _map_dimension(mapper, experiment, f"{field_path}", shot)\n'
                out += f'{indent}for i in range({size_var}):\n'
                
                # Extract child struct name
                type_name = field.type_name
                match = re.search(r'<([\w: ]+)>', type_name)
                child_struct_name = match.group(1) if match else type_name.replace('*', '')
                child_struct_name = child_struct_name.strip()
                
                child_path_expr = f'f"{field_path}[{{i}}]"'
                # We need to pass the current path prefix to the next recursion
                # In the generated code, we'll use a local path_prefix
                out += f'{indent}    path_prefix_{indent_level} = f"{field_path}[{{i}}]"\n'
                
                # Recursion needs a bit of trickery to handle the path prefix correctly in the generated code
                # Let's simplify and use the actual variable names in the generated code
                
                # Refined approach: use f-strings in the generated code
                def get_nested_calls(s_name, p_prefix, level):
                    nested_out = ""
                    n_indent = "    " * level
                    s_def = structures_map.get(s_name)
                    if not s_def: return ""
                    
                    for f in s_def.fields:
                        f_path = f"{p_prefix}/{f.name}"
                        if f.is_vector and f.is_struct:
                            # Too complex for a simple recursive string generation without generating more code
                            # We'll stick to the iterative code generation
                            pass
                    return nested_out

                # Let's use a simpler approach for the generator recursion
                out += process_struct_iterative(child_struct_name, f"path_prefix_{indent_level}", indent_level + 1)
                
            elif field.is_struct:
                # Single structure
                out += f'\n{indent}# Structure: {field.name}\n'
                struct_path = f'{{path_prefix}}/{field.name}'
                child_path_var = f"path_{field.name}_{indent_level}"
                out += f'{indent}{child_path_var} = f"{struct_path}"\n'
                
                child_struct_name = field.type_name.replace('*', '').strip()
                out += process_struct_iterative(child_struct_name, child_path_var, indent_level)
                
            else:
                # Leaf field
                field_path = f'{{path_prefix}}/{field.name}'
                out += f'{indent}_map_field(mapper, experiment, f"{field_path}", shot)\n'
        
        return out

    # Re-writing process_struct to be more robust for Python generation
    def process_struct_iterative(struct_name, path_var_name, indent_level):
        out = ""
        indent = "    " * indent_level
        
        if struct_name not in structures_map and f"{struct_name}_struct" in structures_map:
            struct_name = f"{struct_name}_struct"
            
        if struct_name not in structures_map:
            return out
            
        struct_def = structures_map[struct_name]
        
        for field in struct_def.fields:
            if field.is_vector and field.is_struct:
                array_name = field.name.replace("_vect", "")
                out += f'\n{indent}# Array: {array_name}\n'
                size_var = f"size_{array_name}_{indent_level}"
                # In the generated code, we use the value of the variable path_var_name
                out += f'{indent}{size_var} = _map_dimension(mapper, experiment, f"{{{path_var_name}}}/{array_name}", shot)\n'
                loop_var = f"i_{indent_level}"
                out += f'{indent}for {loop_var} in range({size_var}):\n'
                child_path_var = f"path_{array_name}_{indent_level}"
                out += f'{indent}    {child_path_var} = f"{{{path_var_name}}}/{array_name}[{{{loop_var}}}]"\n'
                
